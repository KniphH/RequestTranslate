import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const entry = `
import {SchemeTonalSpot, Hct, argbFromHex, hexFromArgb} from '@material/material-color-utilities';
const seeds = {purple:'#6750A4', blue:'#415F91', green:'#386A5D', warm:'#984715', rose:'#984061', gray:'#676767'};
const roles = ['primary','onPrimary','primaryContainer','onPrimaryContainer','secondaryContainer','onSecondaryContainer',
  'surface','surfaceContainerLow','surfaceContainer','surfaceContainerHigh','onSurface','onSurfaceVariant',
  'outline','outlineVariant','error','onError','errorContainer','onErrorContainer'];
const output = {};
for (const [name, seed] of Object.entries(seeds)) {
  output[name] = {};
  for (const dark of [false, true]) {
    const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
    output[name][dark ? 'dark' : 'light'] = Object.fromEntries(roles.map(role => [role, hexFromArgb(scheme[role])]));
  }
}
process.stdout.write(JSON.stringify(output, null, 2) + '\\n');
`;
const result = await build({
  stdin: {contents: entry, resolveDir: process.cwd(), loader: 'js'},
  bundle: true, platform: 'node', format: 'cjs', write: false
});
const bundle = join(tmpdir(), 'requesttranslate-m3-generator.cjs');
writeFileSync(bundle, result.outputFiles[0].text);
const palettes = execFileSync(process.execPath, [bundle], {encoding: 'utf8'});
writeFileSync('lib/m3-palettes.json', palettes);


writeFileSync('lib/m3-palettes.js', '/* Generated by npm run colors. */\nwindow.RTM3Palettes = ' + JSON.stringify(JSON.parse(palettes)) + ';\n');
